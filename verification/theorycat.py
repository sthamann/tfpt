def build_parser():
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--json", action="store_true", help="machine-readable JSON output")
    parser = argparse.ArgumentParser(
        prog="theorycat",
        description="Query the generated TFPT theory graph (verification/theory_graph.json).",
        parents=[common],
    )
    parser.add_argument("--no-rebuild", action="store_true",
                        help="skip the lazy staleness rebuild")
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("stats", parents=[common], help="counts + verdict/outcome distributions")

    p = sub.add_parser("claim", parents=[common], help="claim node + compact edges")
    p.add_argument("id")

    p = sub.add_parser("tried", parents=[common],
                       help="contracts + RH records + scorecard rows matching a regex")
    p.add_argument("regex")
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("kills", parents=[common],
                       help="everything killed (rh KILLED + contract killed/refuted/fail + scorecard kill_channel)")
    p.add_argument("regex", nargs="?", default=None)
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("open", parents=[common],
                       help="open fronts: claims [O]/Open* + rh OPEN by family")
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("dossier", parents=[common], help="full node + all edges")
    p.add_argument("node_id")

    p = sub.add_parser("findings", parents=[common],
                       help="verdict-carrying sentences (refutes|no_go|supports|open) matching a regex")
    p.add_argument("regex")
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("lean", parents=[common],
                       help="lean files matching regex (path/header/declarations)")
    p.add_argument("regex")
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("recheck", parents=[common],
                       help="claims whose verified_by scripts changed on disk (hash binding)")

    p = sub.add_parser("why", parents=[common],
                       help="claim contract: statement, premises, proof, hash status")
    p.add_argument("id")

    p = sub.add_parser("fit", parents=[common],
                       help="constraints + transitions touching an object/theme")
    p.add_argument("regex")
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("next", parents=[common],
                       help="ranked open fronts (heuristic score)")
    p.add_argument("--goal", default=None, metavar="CLAIM")
    p.add_argument("--limit", type=int, default=20, metavar="N")

    p = sub.add_parser("contradictions", parents=[common],
                       help="contradicts edges + refutes/no_go findings + tensions")
    p.add_argument("--limit", type=int, default=30, metavar="N")

    p = sub.add_parser("brief", parents=[common],
                       help="session work package for a topic regex (<60 lines)")
    p.add_argument("regex")

    p = sub.add_parser("path", parents=[common],
                       help="shortest depends_on/supersedes path between two claims (BFS)")
    p.add_argument("claim_a")
    p.add_argument("claim_b")
    return parser


def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    if not os.path.isfile(GRAPH_PATH):
        sys.stderr.write(
            "theory graph missing: run: python verification/build_theory_graph.py\n"
        )
        sys.exit(2)
    maybe_rebuild(no_rebuild=bool(getattr(args, "no_rebuild", False)))
    g = Graph(load_graph())
    as_json = bool(getattr(args, "json", False))
    if args.cmd == "stats":
        return cmd_stats(g, as_json)
    if args.cmd == "claim":
        return cmd_claim(g, args.id, as_json)
    if args.cmd == "tried":
        return cmd_tried(g, args.regex, max(1, args.limit), as_json)
    if args.cmd == "kills":
        return cmd_kills(g, args.regex, max(1, args.limit), as_json)
    if args.cmd == "open":
        return cmd_open(g, max(1, args.limit), as_json)
    if args.cmd == "dossier":
        return cmd_dossier(g, args.node_id, as_json)
    if args.cmd == "findings":
        return cmd_findings(g, args.regex, max(1, args.limit), as_json)
    if args.cmd == "lean":
        return cmd_lean(g, args.regex, max(1, args.limit), as_json)
    if args.cmd == "recheck":
        return cmd_recheck(g, as_json)
    if args.cmd == "why":
        return cmd_why(g, args.id, as_json)
    if args.cmd == "fit":
        return cmd_fit(g, args.regex, max(1, args.limit), as_json)
    if args.cmd == "next":
        return cmd_next(g, args.goal, max(1, args.limit), as_json)
    if args.cmd == "contradictions":
        return cmd_contradictions(g, max(1, args.limit), as_json)
    if args.cmd == "brief":
        return cmd_brief(g, args.regex, as_json)
    if args.cmd == "path":
        return cmd_path(g, args.claim_a, args.claim_b, as_json)
    parser.error("unknown command")
    return 2


if __name__ == "__main__":
    sys.exit(main())
