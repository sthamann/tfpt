LINE_WIDTH = 120
ROUND_TOKEN_RE = re.compile(r"r(\d+)", re.I)


def sha256_file(path):
    import hashlib
    h = hashlib.sha256()
    try:
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                h.update(chunk)
    except OSError:
        return None
    return h.hexdigest()


def script_hash_status(g, script_nid):
    """Compare the graph's script_sha256 with the file on disk."""
    a = g.node(script_nid)["attrs"]
    want = a.get("script_sha256")
    path = os.path.join(VERIF_DIR, script_nid.split(":", 1)[1] + ".py")
    if not os.path.isfile(path):
        return "FEHLT"
    if not want:
        return "ohne Hash"
    return "aktuell" if sha256_file(path) == want else "GEÄNDERT"


def clip(text, width=LINE_WIDTH):
    text = " ".join(str(text if text is not None else "").split())
    if len(text) <= width:
        return text
    return text[: width - 3] + "..."


def load_graph():
    if not os.path.isfile(GRAPH_PATH):
        sys.stderr.write(
            "theory graph missing: run: python verification/build_theory_graph.py\n"
        )
        sys.exit(2)
    with open(GRAPH_PATH, "r", encoding="utf-8") as fh:
        return json.load(fh)


def maybe_rebuild(no_rebuild=False):
    """Lazy staleness gate: same source-hash logic as --check; on drift
    rebuild once (~2 s) with a stderr note.  --no-rebuild disables."""
    if no_rebuild:
        return
    try:
        sys.path.insert(0, VERIF_DIR)
        import build_theory_graph as btg
    except Exception:
        return
    try:
        with open(GRAPH_PATH, "r", encoding="utf-8") as fh:
            graph = json.load(fh)
    except (OSError, json.JSONDecodeError):
        return
    try:
        stale = btg.stale_sources(graph)
    except Exception:
        return
    if not stale:
        return
    sys.stderr.write("[theorycat] graph rebuilt (stale)\n")
    subprocess.run(
        [sys.executable, os.path.join(VERIF_DIR, "build_theory_graph.py")],
        check=False,
    )


def emit_json(obj):
    sys.stdout.write(
        json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    )


class Graph:
    def __init__(self, payload):
        self.meta = payload.get("meta") or {}
        self.nodes = payload.get("nodes") or []
        self.edges = payload.get("edges") or []
        self.by_id = {n["id"]: n for n in self.nodes}
        self.out_edges = defaultdict(list)
        self.in_edges = defaultdict(list)
        for e in self.edges:
            self.out_edges[e["src"]].append(e)
            self.in_edges[e["dst"]].append(e)

    def node(self, nid):
        return self.by_id.get(nid)


def as_claim_id(graph, arg):
    """Accept 'EM.FP.01' or 'claim:EM.FP.01'."""
    if arg in graph.by_id:
        return arg
    pref = "claim:" + arg
    if pref in graph.by_id:
        return pref
    return None


def fmt_date(raw):
    raw = raw or ""
    if len(raw) == 8 and raw.isdigit():
        return f"{raw[:4]}-{raw[4:6]}-{raw[6:]}"
    return raw or "-"


def recency_key(kind, node):
    """contracts: YYYYMMDD int; rh: first round number; else 0."""
    a = node["attrs"]
    if kind == "contract":
        try:
            return int(a.get("date") or 0)
        except (TypeError, ValueError):
            return 0
    if kind == "rh":
        m = ROUND_TOKEN_RE.search(a.get("round") or "")
        return int(m.group(1)) if m else 0
    return 0


