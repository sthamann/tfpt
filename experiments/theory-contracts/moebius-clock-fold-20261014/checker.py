"""Moebius x Z4 clock fold of ONE chiral complex seam channel.

Standalone exact checks; no paper/ledger promotion.  Proofs and scope: PROOF.md.

F1  Lift: the quarter rotation of the core circle (4 arcs of length l) lifts to
    the Moebius boundary circle (length 8l, double cover of the core) as a shift
    g by l of order 8 with g^4 = deck.  Folding ONE chiral lattice fermion on the
    8l ring into eight arc channels is a unitary block diagonalisation: channel k
    carries the twist k/8 (periodic ring) resp. (k+1/2)/8 (antiperiodic ring).
F2  Class of the geometric clock in E8: periodic ring -> g^2 has centraliser
    A3+D5 and the Z4 grade census 52/64/60/64 of the TFPT glue grading C;
    g^4 has centraliser D8.  Antiperiodic ring never gives A3+D5.  The periodic
    result is independent of the spin lift mu -> mu+e1.
F3  In fold coordinates the A3 and D5 factors contain spinor roots (4+8, 16+24):
    the TFPT grade-0 structure is not generated by bilinears of the folded
    channels; the deck-fixed D8 is not the bilinear D8 (48 bilinear + 64 spinor).
"""
from fractions import Fraction as F
from itertools import product, combinations
from collections import Counter
from pathlib import Path
import json
import numpy as np

checks = {}
def require(name, cond):
    if not bool(cond):
        raise RuntimeError(name)
    checks[name] = True

# ------------------------------------------------------------------ F1 lift
l = 5                        # sites per arc (any l >= 2)
Nb = 8 * l                   # Moebius boundary ring
shift = lambda s: np.roll(np.eye(Nb), s, axis=0)
g = shift(l)
deck = shift(4 * l)
require("lift_order_8", all(not np.allclose(np.linalg.matrix_power(g, n), np.eye(Nb)) for n in range(1, 8))
        and np.allclose(np.linalg.matrix_power(g, 8), np.eye(Nb)))
require("lift_fourth_power_is_deck", np.allclose(np.linalg.matrix_power(g, 4), deck))
require("deck_is_free_involution", np.allclose(deck @ deck, np.eye(Nb)) and np.trace(deck) == 0)

def ring_hamiltonian(N, bc):          # chiral lattice fermion: H = sum (-i/2)(c+_{x+1}c_x - h.c.)
    H = np.zeros((N, N), complex)
    for x in range(N):
        y, ph = (x + 1) % N, (bc if x == N - 1 else 1)
        H[y, x] += -0.5j * ph
        H[x, y] += 0.5j * np.conj(ph)
    return H

def twisted_shift(N, s, bc):        # shift by s, phase bc on wrapped sites
    M = np.zeros((N, N), complex)
    for x in range(N):
        M[(x + s) % N, x] = bc if x + s >= N else 1
    return M

for bc, off in ((1, F(0)), (-1, F(1, 2))):
    H = ring_hamiltonian(Nb, bc)
    gb = twisted_shift(Nb, l, bc)
    require(f"clock_commutes_with_H_bc{bc}", np.allclose(gb @ H, H @ gb))
    require(f"clock_order8_bc{bc}", np.allclose(np.linalg.matrix_power(gb, 8), bc * np.eye(Nb)))
    big = np.sort(np.linalg.eigvalsh(H))
    small = []
    for k in range(8):
        tw = np.exp(2j * np.pi * float((k + off) / 8))       # channel twist
        small += list(np.linalg.eigvalsh(ring_hamiltonian(l, tw)))
    require(f"fold_spectrum_identity_bc{bc}", np.allclose(big, np.sort(small), atol=1e-12))
    # explicit fold unitary: psi_j(x) = psi(x + j l), channel chi_k = sum_j w^{-jk} psi_j
    U = np.zeros((Nb, Nb), complex)
    for k in range(8):
        for x in range(l):
            for j in range(8):
                U[k * l + x, (x + j * l) % Nb] = np.exp(-2j * np.pi * float((k + off) * j / 8)) / np.sqrt(8)
    require(f"fold_unitary_bc{bc}", np.allclose(U @ U.conj().T, np.eye(Nb)))
    Hf = U @ H @ U.conj().T
    blocks = np.zeros_like(Hf)
    for k in range(8):
        blocks[k*l:(k+1)*l, k*l:(k+1)*l] = Hf[k*l:(k+1)*l, k*l:(k+1)*l]
    require(f"fold_block_diagonal_bc{bc}", np.allclose(Hf, blocks, atol=1e-12))
    gf = U @ gb @ U.conj().T
    eig = np.array([np.exp(-2j*np.pi*float((k+off)/8)) for k in range(8) for _ in range(l)])
    require(f"clock_eigenvalue_per_channel_bc{bc}", np.allclose(gf, np.diag(eig), atol=1e-12))

# --------------------------------------------------------------- E8 model
roots = []
for i, j in combinations(range(8), 2):
    for a, b in product((1, -1), repeat=2):
        v = [F(0)] * 8; v[i] = F(a); v[j] = F(b); roots.append(tuple(v))
for sg in product((1, -1), repeat=8):
    if sg.count(-1) % 2 == 0:
        roots.append(tuple(F(t, 2) for t in sg))
require("e8_roots", len(roots) == 240)
dot = lambda a, b: sum(x * y for x, y in zip(a, b))
spinor = lambda r: r[0].denominator == 2

def components(R):
    seen, out = set(), []
    for i in range(len(R)):
        if i in seen: continue
        st, c = [i], []; seen.add(i)
        while st:
            a = st.pop(); c.append(R[a])
            for b in range(len(R)):
                if b not in seen and dot(R[a], R[b]) != 0:
                    seen.add(b); st.append(b)
        rank = np.linalg.matrix_rank(np.array([[float(x) for x in r] for r in c]))
        n = len(c)
        name = {(12, 3): "A3", (40, 5): "D5", (112, 8): "D8", (60, 6): "D6", (2, 1): "A1",
                (126, 7): "E7", (56, 7): "A7", (24, 4): "D4"}.get((n, rank), f"?{n},{rank}")
        out.append((name, n, n - sum(map(spinor, c)), sum(map(spinor, c))))
    return sorted(out)

def cent(mu):
    return components([r for r in roots if dot(r, mu).denominator == 1])

e1 = tuple([F(1)] + [F(0)] * 7)
results_e8 = {}
for bc, off in (("periodic", F(0)), ("antiperiodic", F(1, 2))):
    for p, nm in ((2, "g2"), (4, "g4")):
        for lift in (0, 1):
            mu = tuple(p * (k + off) / 8 + lift * e1[k] for k in range(8))
            results_e8[f"{bc}_{nm}_lift{lift}"] = cent(mu)

for lift in (0, 1):
    require(f"periodic_clock_centraliser_A3_D5_lift{lift}",
            [c[0] for c in results_e8[f"periodic_g2_lift{lift}"]] == ["A3", "D5"])
    require(f"periodic_deck_centraliser_D8_lift{lift}",
            [c[0] for c in results_e8[f"periodic_g4_lift{lift}"]] == ["D8"])
require("antiperiodic_never_A3_D5",
        all([c[0] for c in results_e8[f"antiperiodic_g2_lift{l_}"]] != ["A3", "D5"] for l_ in (0, 1)))

mu_fold = tuple(F(k, 4) for k in range(8))
mu_C = tuple([F(1, 2)] * 5 + [F(0)] * 3)          # TFPT glue grade C
grade = lambda mu, r: int(4 * dot(r, mu)) % 4
census_fold = Counter(grade(mu_fold, r) for r in roots)
census_C = Counter(grade(mu_C, r) for r in roots)
require("grade_census_equal_52_64_60_64", dict(census_fold) == dict(census_C) == {0: 52, 1: 64, 2: 60, 3: 64})
require("C_centraliser_is_bilinear_A3_D5", cent(mu_C) == [("A3", 12, 12, 0), ("D5", 40, 40, 0)])
require("fold_centraliser_needs_spinors", results_e8["periodic_g2_lift0"] == [("A3", 12, 4, 8), ("D5", 40, 16, 24)])
require("fold_deck_D8_is_not_bilinear_D8", results_e8["periodic_g4_lift0"] == [("D8", 112, 48, 64)])
odd = [r for r in roots if grade(mu_fold, r) % 2]
require("fold_odd_grades_half_bilinear", sum(map(spinor, odd)) == 64 and len(odd) == 128)

results = {
    "contract": "moebius-clock-fold-20261014",
    "arc_sites": l,
    "e8_centralisers": {k: [list(c) for c in v] for k, v in results_e8.items()},
    "grade_census_fold_clock": {str(k): census_fold[k] for k in sorted(census_fold)},
    "checks": checks, "n_checks": len(checks), "verdict": "PARTIAL",
}
Path(__file__).with_name("results.json").write_text(json.dumps(results, indent=2) + "\n")
print(f"{len(checks)}/{len(checks)} checks passed")
