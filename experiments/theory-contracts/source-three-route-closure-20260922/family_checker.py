    need(simplify_matrix(deck_lift * family_projector - family_projector * deck_lift) == sp.zeros(4),
         'deck lift preserves 3+1 splitting')
    need(all(sp.simplify(matrix.det()) == 1 for matrix in loop_lifts),
         'puncture SU4 lifts have determinant one')
    need(sp.simplify(deck_lift.det()) == 1, 'deck SU4 lift has determinant one')
    beta = sp.diag(r + sp.Rational(1, 2), r + sp.Rational(1, 2),
                   r + sp.Rational(1, 2), -3 * r - sp.Rational(3, 2))
    need(all(beta * matrix == matrix * beta for matrix in loop_lifts + [deck_lift]),
         'covering family weights preserve puncture and deck block structure')

