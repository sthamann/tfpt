def need(condition, message):
    if not bool(condition):
        raise RuntimeError(message)


def simplify_matrix(matrix):
    return matrix.applyfunc(lambda entry: sp.simplify(sp.expand(entry)))


def matrix_key(matrix):
    return tuple(sp.simplify(sp.expand(entry)) for entry in matrix)


def matrix_string(matrix):
    return str(matrix)


def enumerate_generated(generators):
    identity = sp.eye(generators[0].rows)
    elements = {matrix_key(identity): identity}
    frontier = deque([identity])
    while frontier:
        old = frontier.popleft()
        for generator in generators:
            new = simplify_matrix(generator * old)
            key = matrix_key(new)
            if key not in elements:
                elements[key] = new
                frontier.append(new)
    return elements


def element_orders(elements):
    result = Counter()
    identity = sp.eye(next(iter(elements.values())).rows)
    for element in elements.values():
        power = element
        order = 1
        while power != identity:
            power = simplify_matrix(power * element)
            order += 1
            need(order <= 24, 'finite group order exceeded audit bound')
        result[order] += 1
    return dict(sorted(result.items()))


def invariant_dimension(matrices, dimension):
    stacked = sp.Matrix.vstack(*[matrix - sp.eye(dimension) for matrix in matrices])
    return dimension - stacked.rank()


def commutant_dimension(matrices):
    variables = sp.symbols('z0:' + str(9))
    Z = sp.Matrix(3, 3, variables)
    equations = []
    for matrix in matrices:
        equations.extend(list(Z * matrix - matrix * Z))
    coefficient = sp.linear_eq_to_matrix(equations, variables)[0]
    return 9 - coefficient.rank()


def wedge2(matrix):
    pairs = [(0, 1), (0, 2), (1, 2)]
    result = sp.zeros(3)
    for column, (i, j) in enumerate(pairs):
        for row, (a, b) in enumerate(pairs):
            result[row, column] = matrix[a, i] * matrix[b, j] - matrix[a, j] * matrix[b, i]
    return simplify_matrix(result)


def symmetric_invariant_dimension(matrices):
    variables = sp.symbols('s0:6')
    symmetric = sp.Matrix([[variables[0], variables[1], variables[2]],
                           [variables[1], variables[3], variables[4]],
                           [variables[2], variables[4], variables[5]]])
    equations = []
    for matrix in matrices:
        equations.extend(list(matrix.T * symmetric * matrix - symmetric))
    coefficient = sp.linear_eq_to_matrix(equations, variables)[0]
    return 6 - coefficient.rank()


def main():
    need(V117.exists() and BOUNDARY.exists(), 'pinned source files are present')
    v117_sha = hashlib.sha256(V117.read_bytes()).hexdigest()
    boundary_sha = hashlib.sha256(BOUNDARY.read_bytes()).hexdigest()
    need(v117_sha == V117_SHA256, 'v117 source pin')
    need(boundary_sha == BOUNDARY_SHA256, 'source-boundary lift checker pin')

    M = sp.Matrix([[0, -(1 + I) / 2, (1 - I) / 2],
                   [-(1 + I) / 2, -I / 2, -sp.Rational(1, 2)],
                   [(1 - I) / 2, -sp.Rational(1, 2), I / 2]])
    U = sp.diag(1, I, -I)
    identity3 = sp.eye(3)
    punctures = [simplify_matrix(U ** k * M * U ** (-k)) for k in range(4)]
    need(all(simplify_matrix(matrix.H * matrix) == identity3 for matrix in punctures),
         'all puncture matrices are unitary')
    need(all(sp.simplify(matrix.det()) == 1 for matrix in punctures),
         'all puncture matrices have determinant one')
    need(all(simplify_matrix(matrix ** 3) == identity3 for matrix in punctures),
         'all puncture matrices have order three')
    need(simplify_matrix(sp.prod(punctures, start=identity3)) == identity3,
         'puncture product relation')

    puncture_group = enumerate_generated(punctures)
    full_group = enumerate_generated([M, U])
    need(len(puncture_group) == 12, 'actual puncture subgroup has order 12')
    need(len(full_group) == 24, 'M,U group has order 24')
    need(all(matrix_key(U * element * U ** (-1)) in puncture_group
             for element in puncture_group.values()),
         'puncture subgroup is normal under deck conjugation')
    need(matrix_key(U ** 2) in puncture_group, 'deck square lies in puncture subgroup')
    need(len(full_group) == 2 * len(puncture_group), 'puncture subgroup has index two')

    trace_histogram = Counter(str(sp.simplify(element.trace()))
                              for element in puncture_group.values())
    full_trace_histogram = Counter(str(sp.simplify(element.trace()))
                                   for element in full_group.values())
    order_histogram = element_orders(puncture_group)
    full_order_histogram = element_orders(full_group)
    need(dict(trace_histogram) == {'3': 1, '-1': 3, '0': 8},
         'A4 character histogram')
    need(order_histogram == {1: 1, 2: 3, 3: 8}, 'A4 order histogram')
    need(dict(full_trace_histogram) == {'3': 1, '-1': 9, '0': 8, '1': 6},
         'full S4 character histogram')
    need(full_order_histogram == {1: 1, 2: 9, 3: 8, 4: 6},
         'full S4 order histogram')

    commutator = simplify_matrix(punctures[0] * punctures[1]
                                 * punctures[0].inv() * punctures[1].inv())
    need(commutator != identity3, 'puncture loops have nontrivial commutator')
    commutator_trace = sp.simplify(commutator.trace())
    need(commutator_trace == -1, 'puncture commutator trace')
    need(commutator ** 2 == identity3, 'puncture commutator has order two')
    primitive_winding_abelian = commutator == identity3
    need(not primitive_winding_abelian,
         'primitive winding Z cannot reproduce nonabelian puncture image')

    invariant_dimensions = {
        'V': invariant_dimension(list(puncture_group.values()), 3),
        'End(V)': commutant_dimension(list(puncture_group.values())),
        'Sym2(V)': symmetric_invariant_dimension(list(puncture_group.values())),
        'Lambda2(V)': invariant_dimension(
            [wedge2(element) for element in puncture_group.values()], 3),
    }
    need(invariant_dimensions == {'V': 0, 'End(V)': 1, 'Sym2(V)': 1, 'Lambda2(V)': 0},
         'A4 invariant dimensions')

    # A rank-three SU(3) local system with these puncture holonomies exists
    # independently of whether the original source selects it.  The global
    # joint Spin(10)-family lift uses D=det(E) directly.  No square-root line
    # and no standalone Spin(10) x SU(4) product bundle are assumed.
    r = sp.symbols('r', integer=True)
    m = sp.Matrix([r, r, r, -2 - 3 * r])
    need(sum(m) == -2, 'integer lift weights have sum -2')
    beta = m + sp.Rational(1, 2) * sp.ones(4, 1)
    need(sum(beta) == 0, 'covering SU4 weights are traceless')
    d = sp.symbols('d')
    c1_even = sp.expand(8 * d)
    c1_first = sp.expand(3 * (c1_even + 16 * r * d))
    c1_second = sp.expand(c1_even + 16 * (-2 - 3 * r) * d)
    c1_total = sp.expand(c1_first + c1_second)
    need(sp.expand(c1_even - 8 * d) == 0, 'even-spinor first Chern class')
    need(sp.expand(c1_first - (24 + 48 * r) * d) == 0,
         'rank-three joint block first Chern class')
    need(sp.expand(c1_second - (-24 - 48 * r) * d) == 0,
         'singlet joint block first Chern class')
    need(sp.expand(c1_total) == 0, 'joint rank-64 first Chern class vanishes')

    # The connection is recorded at the exact block-form level.  A_F is
    # traceless SU(3) data; its flat marked holonomy is an additional datum.
    a, f1, f2 = sp.symbols('a f1 f2')
    A_F = sp.diag(f1, f2, -f1 - f2)
    family_connection = sp.diag(r * a + f1, r * a + f2,
                                r * a - f1 - f2, (-2 - 3 * r) * a)
    need(A_F.trace() == 0, 'A_F is traceless SU3 connection data')
    need(family_connection.shape == (4, 4), 'family connection has 3+1 block size')

    loop_lifts = [sp.diag(matrix, 1) for matrix in punctures]
    deck_lift = sp.diag(U, 1)
    family_projector = sp.diag(1, 1, 1, 0)
