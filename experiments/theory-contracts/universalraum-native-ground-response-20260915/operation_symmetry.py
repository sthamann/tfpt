RHO5=(8,6,4,2,0); RHO3=(4,2,0)  # doubled coordinates
def weyl_d(rho):
    n=len(rho); out=[]
    for perm in permutations(range(n)):
        ps=(-1)**sum(perm[i]>perm[j] for i in range(n) for j in range(i+1,n))
        for fm in range(2**n):
            if bin(fm).count('1')%2: continue
            signs=tuple(-1 if (fm>>i)&1 else 1 for i in range(n))
            out.append((ps,tuple(signs[i]*rho[perm[i]] for i in range(n))))
    return out
