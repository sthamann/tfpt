"""Relax the Phi-completed m=4 wall cores under the actual H0.

Two non-mirror source-module sectors are treated separately:

  1202 = (bar4, barSym2, 1, barSym2), core Phi Omega s Omega
  2102 = (barSym2, bar4, 1, barSym2), core Omega Phi s Omega

Each sector has dimension 409600.  H0 is applied matrix-free as a sum of four
local event Laplacians.  The calculation first builds the Lanczos/Krylov space
generated by the completed core, then independently asks for the four lowest
eigenpairs of the whole fixed source-module sector using a generic random
start.  This is a local finite-sector numerical test, not a chain vacuum or
wall-EFT claim.
"""
