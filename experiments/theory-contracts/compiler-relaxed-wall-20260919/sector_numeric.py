def require(condition: bool, label: str, checks: list[str]) -> None:
    if not bool(condition):
        raise RuntimeError(label)
    checks.append(label)


def load_module(name: str, path: Path):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def sym_basis() -> np.ndarray:
    """Orthonormal Sym^2(C^4) basis in the ordered tensor-square basis."""
    pairs = [(a, b) for a in range(4) for b in range(a, 4)]
    basis = np.zeros((16, 10), dtype=np.complex128)
    for column, (a, b) in enumerate(pairs):
        if a == b:
            basis[4 * a + b, column] = 1
        else:
            basis[4 * a + b, column] = 1 / np.sqrt(2)
            basis[4 * b + a, column] = 1 / np.sqrt(2)
    return basis


def grouped(values: np.ndarray, tolerance: float = 3e-10) -> list[dict[str, Any]]:
    groups: list[list[float | int]] = []
    for value in np.sort(np.real_if_close(values).real):
        if not groups or abs(value - float(groups[-1][0])) > tolerance:
            groups.append([float(value), 1])
        else:
            groups[-1][1] = int(groups[-1][1]) + 1
    return [{"value": float(value), "multiplicity": int(mult)} for value, mult in groups]


@dataclass
class NativeData:
    rays: list[np.ndarray]
    reflections: list[np.ndarray]
    source_actions: dict[int, list[np.ndarray]]
    local_laplacians: dict[int, np.ndarray]
    phi: np.ndarray
    omega: np.ndarray


def build_native(checks: list[str]) -> NativeData:
    source = load_module("relaxed_wall_native_source", REPO / SOURCE_REL)
    rays = source.source_rays()
    require(len(rays) == 60, "native source has sixty rays", checks)
    bplus = sym_basis()
    require(np.max(np.abs(bplus.conj().T @ bplus - np.eye(10))) < 2e-15,
            "symmetric-square basis is orthonormal", checks)

    reflections = []
    actions: dict[int, list[np.ndarray]] = {0: [], 1: [], 2: []}
    for ray in rays:
        reflection = np.eye(4, dtype=np.complex128) - np.outer(ray, ray.conj()) / 2
        reflections.append(reflection)
        actions[0].append(np.ones((1, 1), dtype=np.complex128))
        actions[1].append(reflection.conj())
        sym_action = bplus.conj().T @ np.kron(reflection, reflection) @ bplus
        actions[2].append(sym_action.conj())
    require(max(np.linalg.norm(r @ r - np.eye(4)) for r in reflections) < 2e-15,
            "native reflections are involutions", checks)

    local_laplacians: dict[int, np.ndarray] = {}
    for charge, dimension in ((0, 1), (1, 4), (2, 10)):
        moment = np.zeros((16 * dimension, 16 * dimension), dtype=np.complex128)
        for source_action, reflection in zip(actions[charge], reflections):
            moment += np.kron(source_action, np.kron(reflection, reflection)) / 60
        laplacian = np.eye(16 * dimension, dtype=np.complex128) - moment
        require(np.linalg.norm(laplacian - laplacian.conj().T) < 3e-14,
                f"charge-{charge} local Laplacian is Hermitian", checks)
        local_laplacians[charge] = laplacian

    # Packet tensors are already expressed in their Schmidt source modules.
    phi = np.eye(4, dtype=np.complex128) / 2
    omega = bplus.T.reshape(10, 4, 4) / np.sqrt(10)
    require(abs(np.linalg.norm(phi) - 1) < 2e-15, "Phi packet is normalized", checks)
    require(abs(np.linalg.norm(omega) - 1) < 2e-15, "Omega packet is normalized", checks)
    return NativeData(rays, reflections, actions, local_laplacians, phi, omega)


class SectorOperator(LinearOperator):
    """H0=sum_e L_e for one fixed four-source module string."""

    def __init__(self, charges: tuple[int, int, int, int], local: dict[int, np.ndarray]):
        self.charges = charges
        self.source_dims = tuple({0: 1, 1: 4, 2: 10}[q] for q in charges)
        self.tensor_dims = self.source_dims + (4, 4, 4, 4, 4)
        self.local = local
        dimension = int(np.prod(self.tensor_dims))
        super().__init__(dtype=np.complex128, shape=(dimension, dimension))

    def _matvec(self, vector: np.ndarray) -> np.ndarray:
        tensor = np.asarray(vector, dtype=np.complex128).reshape(self.tensor_dims)
        answer = np.zeros_like(tensor)
        axis_count = len(self.tensor_dims)
        for edge, charge in enumerate(self.charges):
            axes = (edge, 4 + edge, 5 + edge)
            rest = tuple(axis for axis in range(axis_count) if axis not in axes)
            permutation = axes + rest
            inverse = np.argsort(permutation)
            moved = tensor.transpose(permutation)
            local_dimension = self.source_dims[edge] * 16
            rows = moved.reshape(local_dimension, -1)
            image = (self.local[charge] @ rows).reshape(moved.shape)
            answer += image.transpose(inverse)
        return answer.reshape(-1)


def make_core(charges: tuple[int, int, int, int], native: NativeData) -> np.ndarray:
    """Construct the completed core in sector 1202 or 2102."""
    scalar = np.ones(1, dtype=np.complex128)
    if charges == (1, 2, 0, 2):
        # Phi_(R1,A) Omega_(R2,BC) s_R3 Omega_(R4,DE)
        tensor = np.einsum(
            "aA,bBC,q,dDE->abqdABCDE",
            native.phi, native.omega, scalar, native.omega,
        )
    elif charges == (2, 1, 0, 2):
        # Omega_(R1,AB) Phi_(R2,C) s_R3 Omega_(R4,DE)
        tensor = np.einsum(
            "aAB,bC,q,dDE->abqdABCDE",
            native.omega, native.phi, scalar, native.omega,
        )
    else:
        raise ValueError(f"unsupported sector {charges}")
    return tensor.reshape(-1)


def lanczos_from_core(
    operator: LinearOperator,
    core: np.ndarray,
    max_steps: int = 32,
    closure_tolerance: float = 2e-12,
) -> dict[str, Any]:
    """Fully reorthogonalized Hermitian Lanczos from one core vector."""
    q = core / np.linalg.norm(core)
    basis: list[np.ndarray] = []
    diagonal: list[float] = []
    off_diagonal: list[float] = []
    closure_residual = np.nan

    for step in range(max_steps):
        basis.append(q.copy())
        image = operator @ q
        alpha = float(np.vdot(q, image).real)
        diagonal.append(alpha)
        residual = image - alpha * q
        if step:
            residual -= off_diagonal[-1] * basis[-2]
        # Two passes make the small projected Jacobi trustworthy even when the
        # Krylov space nearly closes.
        for _ in range(2):
            for old in basis:
                residual -= np.vdot(old, residual) * old
        beta = float(np.linalg.norm(residual))
        closure_residual = beta
        if beta < closure_tolerance:
            break
        if step + 1 == max_steps:
            break
        off_diagonal.append(beta)
        q = residual / beta

    # off_diagonal contains links among the retained basis columns.  If the
    # last residual did not close, its beta is deliberately not part of T.
    expected_links = max(0, len(diagonal) - 1)
    off_diagonal = off_diagonal[:expected_links]
    eigenvalues, eigenvectors = eigh_tridiagonal(
        np.asarray(diagonal), np.asarray(off_diagonal), lapack_driver="stev"
    )
    ground_coefficients = eigenvectors[:, 0]
    lifted = sum(coefficient * vector for coefficient, vector in zip(ground_coefficients, basis))
    lifted_residual = float(np.linalg.norm(operator @ lifted - eigenvalues[0] * lifted))
    gram_error = float(np.max(np.abs(
        np.column_stack(basis).conj().T @ np.column_stack(basis) - np.eye(len(basis))
    )))
    return {
        "basis": basis,
        "dimension": len(basis),
        "closed": bool(closure_residual < closure_tolerance),
        "closure_residual": float(closure_residual),
        "jacobi_diagonal": diagonal,
        "jacobi_off_diagonal": off_diagonal,
        "projected_eigenvalues": eigenvalues.tolist(),
        "projected_ground_coefficients": ground_coefficients.tolist(),
        "projected_ground_energy": float(eigenvalues[0]),
        "projected_ground_full_residual": lifted_residual,
        "basis_gram_max_error": gram_error,
    }


def full_sector_lowest(
    operator: LinearOperator,
    core: np.ndarray,
    krylov_basis: list[np.ndarray],
    seed: int,
) -> dict[str, Any]:
    rng = np.random.default_rng(seed)
    start = rng.normal(size=operator.shape[0]) + 1j * rng.normal(size=operator.shape[0])
    start /= np.linalg.norm(start)
    values, vectors = eigsh(
        operator,
        k=4,
        which="SA",
        v0=start,
        tol=3e-11,
        maxiter=700,
        ncv=24,
    )
    order = np.argsort(values)
    values = values[order]
    vectors = vectors[:, order]
    residuals = [
        float(np.linalg.norm(operator @ vectors[:, index] - values[index] * vectors[:, index]))
        for index in range(4)
    ]
    core_weights = [float(abs(np.vdot(core, vectors[:, index])) ** 2) for index in range(4)]
    krylov_weights = [
        float(sum(abs(np.vdot(q, vectors[:, index])) ** 2 for q in krylov_basis))
        for index in range(4)
    ]
    gram_error = float(np.max(np.abs(vectors.conj().T @ vectors - np.eye(4))))
    return {
        "lowest_four": values.tolist(),
        "gap_first_to_second": float(values[1] - values[0]),
        "residuals": residuals,
        "max_residual": max(residuals),
        "eigenvector_gram_max_error": gram_error,
        "core_weights": core_weights,
        "core_krylov_subspace_weights": krylov_weights,
    }


def clean_krylov(data: dict[str, Any]) -> dict[str, Any]:
    return {key: value for key, value in data.items() if key != "basis"}


def main() -> None:
    checks: list[str] = []
    for relative, expected in PINS.items():
        observed = hashlib.sha256((REPO / relative).read_bytes()).hexdigest()
        require(observed == expected, f"pinned input {relative}", checks)

    native = build_native(checks)
    local_spectra = {
        str(charge): grouped(np.linalg.eigvalsh(laplacian))
        for charge, laplacian in native.local_laplacians.items()
    }
    sectors = {
        "1202_end": (1, 2, 0, 2),
        "2102_center": (2, 1, 0, 2),
    }
    output: dict[str, Any] = {}
    for index, (name, charges) in enumerate(sectors.items()):
        operator = SectorOperator(charges, native.local_laplacians)
        core = make_core(charges, native)
        require(operator.shape == (409600, 409600), f"{name} sector dimension", checks)
        require(abs(np.linalg.norm(core) - 1) < 3e-13, f"{name} core is normalized", checks)
        expectation = float(np.vdot(core, operator @ core).real)
        raw_residual = operator @ core - expectation * core
        residual_norm_squared = float(np.vdot(raw_residual, raw_residual).real)
        require(abs(expectation - 1.25) < 2e-13, f"{name} core H0 expectation is five quarters", checks)
        require(abs(residual_norm_squared - 3 / 80) < 2e-13,
                f"{name} core leakage norm squared is three over eighty", checks)

        krylov = lanczos_from_core(operator, core)
        full = full_sector_lowest(operator, core, krylov["basis"], 20260919 + index)
        require(full["max_residual"] < 2e-8, f"{name} full-sector Ritz residuals", checks)
        output[name] = {
            "charges": list(charges),
            "source_modules": [
                {0: "1", 1: "bar4", 2: "barSym2"}[charge] for charge in charges
            ],
            "dimension": operator.shape[0],
            "core_expectation": expectation,
            "core_external_residual_norm_squared": residual_norm_squared,
            "krylov": clean_krylov(krylov),
            "full_sector": full,
            "krylov_minus_full_ground": float(
                krylov["projected_ground_energy"] - full["lowest_four"][0]
            ),
        }

    expected_end = float(0.5 + (8 - np.sqrt(19)) / 5)
    require(output["1202_end"]["krylov"]["closed"],
            "end-core Krylov space closes", checks)
    require(output["1202_end"]["krylov"]["dimension"] == 2,
            "end-core Krylov space has dimension two", checks)
    require(abs(output["1202_end"]["krylov"]["projected_ground_energy"] - expected_end) < 2e-12,
            "end-core relaxed energy matches half plus eight minus sqrt nineteen over five", checks)
    require(output["2102_center"]["krylov"]["closed"],
            "center-core native Krylov space closes numerically", checks)
    require(output["2102_center"]["krylov"]["dimension"] == 6,
            "center-core native Krylov space has dimension six", checks)
    for name in sectors:
        require(abs(output[name]["krylov_minus_full_ground"]) < 2e-10,
                f"{name} Krylov ground matches full fixed-sector ground numerically", checks)
        require(abs(output[name]["full_sector"]["core_krylov_subspace_weights"][0] - 1) < 2e-10,
                f"{name} fixed-sector ground lies in core Krylov space numerically", checks)
    center_minus_end = float(
        output["2102_center"]["full_sector"]["lowest_four"][0]
        - output["1202_end"]["full_sector"]["lowest_four"][0]
    )
    require(center_minus_end < -1e-4,
            "center source-sector ground is below boundary source-sector ground", checks)

    result = {
        "status": "PASS_NUMERICAL_CLOSED_KRYLOV_EQUALS_FIXED_SECTOR_GROUND",
        "verdict": (
            "BOTH_CORE_KRYLOV_SPACES_CLOSE_AND_MATCH_THE_OBSERVED_FIXED_SECTOR_GROUNDS; "
            "NO_FULL_SOURCE_VACUUM_OR_CHAIN_EFT_CLAIM"
        ),
        "kappa": 1.0,
        "J": 0.0,
        "mu": 0.0,
        "pins": {str(path): digest for path, digest in PINS.items()},
        "local_laplacian_spectra": local_spectra,
        "expected_end_core_relaxed_energy": {
            "exact": "1/2+(8-sqrt(19))/5",
            "numeric": expected_end,
        },
        "center_minus_boundary_ground_energy": center_minus_end,
        "mirror_sectors_by_exact_open_chain_reversal": {
            "1202_end": "2021_end",
            "2102_center": "2012_center",
            "scope": "same spectra by reversing the four sources and five matter sites; mirrors were not separately diagonalized",
        },
        "ground_vector_storage": (
            "Regenerate the deterministic native Krylov basis with this script and combine it "
            "with projected_ground_coefficients in each sector; no extra binary artifact is used."
        ),
        "sectors": output,
        "checks": checks,
        "check_count": len(checks),
        "numerical_boundary": (
            "The full-sector eigensolves cover only the named fixed finite source modules in a "
            "four-edge, five-matter patch.  They do not minimize over other source modules or "
            "longer chains and do not establish a wall EFT, vacuum, Dirac mode, or physical particle."
        ),
    }
    OUT_JSON.write_text(json.dumps(result, indent=2, sort_keys=True) + "\n")

    lines = [
        "PHI-COMPLETED FOUR-SOURCE CORE: ACTUAL H0 RELAXATION",
        "",
        f"status: {result['status']}",
        "kappa=1, J=mu=0",
        "",
    ]
    for name in sectors:
        data = output[name]
        krylov = data["krylov"]
        full = data["full_sector"]
        lines.extend([
            name,
            f"  charges/modules: {data['charges']} / {data['source_modules']}",
            f"  dimension: {data['dimension']}",
            f"  core expectation: {data['core_expectation']:.15f}",
            f"  core leakage norm^2: {data['core_external_residual_norm_squared']:.15f}",
            f"  Krylov dimension/closed: {krylov['dimension']} / {krylov['closed']}",
            f"  Krylov Jacobi diagonal: {krylov['jacobi_diagonal']}",
            f"  Krylov Jacobi off-diagonal: {krylov['jacobi_off_diagonal']}",
            f"  Krylov projected ground: {krylov['projected_ground_energy']:.15f}",
            f"  Krylov lifted residual: {krylov['projected_ground_full_residual']:.3e}",
            f"  full-sector lowest four: {full['lowest_four']}",
            f"  full-sector gap E1-E0: {full['gap_first_to_second']:.15f}",
            f"  full-sector residual max: {full['max_residual']:.3e}",
            f"  core weights in lowest four: {full['core_weights']}",
            f"  core-Krylov weights in lowest four: {full['core_krylov_subspace_weights']}",
            f"  Krylov ground minus sector ground: {data['krylov_minus_full_ground']:.15f}",
            "",
        ])
    lines.extend([
        f"center minus boundary fixed-sector ground: {center_minus_end:.15f}",
        "mirrors by exact open-chain reversal: 1202 <-> 2021, 2102 <-> 2012",
        "",
        "Ground-vector recipe:",
        "  Regenerate the deterministic native Krylov basis with this script and combine",
        "  it with projected_ground_coefficients from the JSON.  The observed full-sector",
        "  ground lies in that Krylov space in both sectors.",
        "",
        "Boundary:",
        "  These are fixed-source-module results for one four-edge patch.  They do not",
        "  minimize over the complete source Hilbert space or longer chains, and they do",
        "  not establish a wall EFT, a chain vacuum, or a physical Dirac excitation.",
        "",
    ])
    OUT_TXT.write_text("\n".join(lines))
    print(json.dumps({
        "status": result["status"],
        "check_count": len(checks),
        "sectors": {
            name: {
                "krylov_dim": output[name]["krylov"]["dimension"],
                "krylov_closed": output[name]["krylov"]["closed"],
                "krylov_ground": output[name]["krylov"]["projected_ground_energy"],
                "sector_ground": output[name]["full_sector"]["lowest_four"][0],
                "sector_gap": output[name]["full_sector"]["gap_first_to_second"],
            }
            for name in sectors
        },
    }, sort_keys=True))


