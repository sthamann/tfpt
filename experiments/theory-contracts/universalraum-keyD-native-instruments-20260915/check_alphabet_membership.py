# Signed permutations on 16 points as (perm, sign) pairs; Schreier transversal
# over permutation parts; the diagonal kernel D is an elementary abelian
# 2-group, so it is the F2-span of the Schreier sign vectors.
def to_ps(M):
    img = tuple(int(x) for x in np.argmax(np.abs(M), axis=0))
    return img, tuple(int(M[img[j], j]) for j in range(16))

def compose(g1, g2):
    p1, s1 = g1; p2, s2 = g2
    return tuple(p1[p2[i]] for i in range(16)), tuple(s1[p2[i]] * s2[i] for i in range(16))

def inv_ps(g):
    p, s = g
    ip = [0]*16
    for i, pi in enumerate(p):
        ip[pi] = i
    ip = tuple(ip)
    return ip, tuple(s[ip[i]] for i in range(16))

def schreier_kernel(gens):
    ident = (tuple(range(16)), (1,)*16)
    reps = {ident[0]: ident}
    queue = [ident]
    diag_vectors = []
    while queue:
        r = queue.pop()
        for g in gens:
            cand = compose(r, g)
            if cand[0] not in reps:
                reps[cand[0]] = cand
                queue.append(cand)
            else:
                d = compose(cand, inv_ps(reps[cand[0]]))
                need(d[0] == ident[0], 'Schreier element is diagonal')
                diag_vectors.append(d[1])
    return reps, diag_vectors

def f2_analysis(diag_vectors):
    basis = {}
    for s in diag_vectors:
        v = 0
        for i, si in enumerate(s):
            if si == -1:
                v |= (1 << i)
        x = v
        while x:
            i = x.bit_length() - 1
            if i in basis:
                x ^= basis[i]
            else:
                basis[i] = x
                break
    def member(bit):
        x = bit
        while x:
            i = x.bit_length() - 1
            if i in basis:
                x ^= basis[i]
            else:
                return False
        return True
    return len(basis), member

