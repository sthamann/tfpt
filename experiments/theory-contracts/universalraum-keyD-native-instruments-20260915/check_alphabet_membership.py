# --- (c) membership in the declared discrete lift groups --------------------
# Every declared lift generator is kron(S, C) with S a SIGNED permutation on the
# 16 spinors and C an UNSIGNED permutation on the 4 colours; products keep this
# form, so every element of <GROUP> and of <GROUP, Clock> is kron(S, C) with
# S in the spin group and C in S4. If u_4 = kron(S, C), entrywise comparison
# forces C = I_4 and S = diag(-1 at spinor 1) =: S1 (colour entries of C are
# 0/1, so a single minus sign at (1,0) cannot come from C; the diagonal then
# fixes S uniquely). Hence u_4 membership reduces exactly to S1 in G_spin.
def kron_factor(g):
    g = np.asarray(g)
    C = np.zeros((4, 4), dtype=np.int64)
    S = None
    for c in range(4):
        for c2 in range(4):
            block = g[np.ix_([4*s + c for s in range(16)], [4*s + c2 for s in range(16)])]
            if np.any(block):
                need(S is None or np.array_equal(block, S) or np.array_equal(block, -S),
                     'kron block structure of a declared lift generator')
                S = block if S is None else S
                C[c, c2] = 1
    return S, C

